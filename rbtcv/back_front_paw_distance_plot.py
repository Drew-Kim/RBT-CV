def _zoomed_nonnegative_axis_bounds(values: Iterable[float]) -> tuple[float, float]:
    """Return a readable tight axis without clipping data or SD ribbons.

    Back/front-paw distance is a continuous line measurement, not a bar chart,
    so a forced zero baseline only obscures meaningful between-group changes.
    The caller supplies all plotted observations plus mean +/- SD edges; this
    helper rounds a small data-driven margin to readable tick values.  Negative
    values remain excluded because this metric and its sample SD are
    nonnegative.
    """
    finite_values = [float(value) for value in values if math.isfinite(float(value))]
    if not finite_values:
        return 0.0, 1.0

    minimum = max(0.0, min(finite_values))
    maximum = max(finite_values)
    span = maximum - minimum
    padding = max(0.02, span * 0.02) if span > 1e-9 else max(0.5, maximum * 0.15)
    lower_value = max(0.0, minimum - padding)
    upper_value = maximum + padding

    # Keep enough vertical room to distinguish nearly identical values while
    # avoiding an overstated chart when every value is identical.
    if upper_value - lower_value < 0.5:
        center = (upper_value + lower_value) / 2.0
        lower_value = max(0.0, center - 0.25)
        upper_value = center + 0.25

    step = _nice_axis_step((upper_value - lower_value) / 6.0)
    lower = max(0.0, math.floor(lower_value / step) * step)
    upper = math.ceil(upper_value / step) * step
    if upper - lower < step * 2:
        upper = lower + (step * 2)
    return lower, upper


def _nice_axis_step(target: float) -> float:
    """Return a 1/2/5-style step near one sixth of the rendered range."""
    if target <= 0 or not math.isfinite(target):
        return 1.0
    magnitude = 10 ** math.floor(math.log10(target))
    normalized = target / magnitude
    for candidate in (1.0, 2.0, 5.0, 10.0):
        if normalized <= candidate:
            return candidate * magnitude
    return 10.0 * magnitude


def _axis_ticks(lower: float, upper: float) -> list[float]:
    step = _nice_axis_step((upper - lower) / 6.0)
    count = max(1, int(round((upper - lower) / step)))
    return [round(lower + (index * step), 10) for index in range(count + 1)]


def _tick_label(value: float) -> str:
    return str(int(value)) if value.is_integer() else f"{value:.1f}"


def _all_bin_values(series: Iterable[TrialPawDistanceSeries]) -> list[float]:
    return [float(value) for item in series for value in item.bin_means if _valid(value)]


def _summary_edges(groups: Iterable[GroupPawDistanceSummary]) -> list[float]:
    values: list[float] = []
    for group in groups:
        for mean, error in zip(group.means, group.standard_deviations):
            if not _valid(mean):
                continue
            values.append(float(mean))
            if _valid(error):
                values.extend((float(mean) - float(error), float(mean) + float(error)))
    return values


def _valid(value: float | None) -> bool:
    return value is not None and math.isfinite(float(value))


def _cell_text(values: tuple[object, ...], index: int | None) -> str:
    if index is None or index >= len(values) or values[index] is None:
        return ""
    value = values[index]
    return str(int(value)) if isinstance(value, float) and value.is_integer() else str(value).strip()


def _cell_float(values: tuple[object, ...], index: int | None) -> float | None:
    if index is None or index >= len(values) or values[index] is None:
        return None
    try:
        value = float(values[index])
    except (TypeError, ValueError):
        return None
    return value if math.isfinite(value) else None


def _cell_int(values: tuple[object, ...], index: int | None) -> int:
    value = _cell_float(values, index)
    return int(value) if value is not None else 0


def _condition_color(condition: str) -> str:
    return {
        "SHAM": SHAM_COLOR,
        "STROKE": STROKE_COLOR,
    }.get(condition.upper(), UNASSIGNED_COLOR)


def _condition_order(condition: str) -> tuple[int, str]:
    normalized = condition.upper()
    return ({"SHAM": 0, "STROKE": 1}.get(normalized, 2), normalized)


def _numeric_key(value: str) -> tuple[int, int | str]:
    return (0, int(value)) if value.isdigit() else (1, value.casefold())


def _trial_sort_key(series: TrialPawDistanceSeries):
    return (
        _condition_order(series.condition),
        _numeric_key(series.cage),
        _numeric_key(series.animal),
        series.trial,
    )
