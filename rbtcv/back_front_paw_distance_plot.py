"""SVG comparisons for calibrated back-paw to front-paw distance.

The workbook's wide frame sheet is deliberately human-friendly: every cell
contains the distance and the matching back-paw position.  This module reads
that sheet, converts valid frames into 10 cm beam bins, and gives every mouse
equal weight in group statistics.  It never fabricates observations across
missing or low-confidence frame gaps.
"""

from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass
import html
import math
from pathlib import Path
import re
import statistics
from typing import Iterable

from .condition_map import ConditionMapStore
from .dataset import ROOT, natural_day_key


OUTPUT_ROOT = ROOT / "outputs"
RESULTS_FILENAME = "RBT_CV_Results.xlsx"
SHEET_NAME = "Back-Front Paw Distance"
CHART_DIRECTORY = "Back_Front paw Distance"
FILE_SUFFIX = ".svg"
GROUP_PREFIX = "back_front_paw_distance_group_comparison_"
# Kept as cleanup identifiers for charts generated by earlier releases.  New
# refreshes do not create trial-to-trial consistency charts.
CONSISTENCY_PREFIX = "back_front_paw_distance_trial_consistency_"
WITHIN_TRIAL_VARIATION_PREFIX = "back_front_paw_distance_within_trial_variation_"
DAY_GROUP_FILENAME = "Day_back_front_paw_distance_group_comparison.svg"
DAY_CONSISTENCY_FILENAME = "Day_back_front_paw_distance_trial_consistency.svg"
DAY_WITHIN_TRIAL_VARIATION_FILENAME = "Day_back_front_paw_distance_within_trial_variation.svg"
BIN_STARTS_CM = tuple(range(0, 90, 10))

SHAM_COLOR = "#1976D2"
STROKE_COLOR = "#D32F2F"
UNASSIGNED_COLOR = "#616161"
ERROR_RANGE_COLOR = "#6B7280"
ERROR_WHISKER_COLOR = "#374151"
FRAME_CELL_RE = re.compile(r"([+-]?\d+(?:\.\d+)?) cm; ([+-]?\d+(?:\.\d+)?) cm")


@dataclass(frozen=True)
class TrialPawDistanceSeries:
    """One trial's mean stance distance within every 10 cm beam bin."""

    day: str
    cage: str
    animal: str
    condition: str
    trial: int
    bin_means: tuple[float | None, ...]
    # Raw valid frame distances are retained for position-controlled
    # within-trial variation.  They are grouped by the same 0--10 through
    # 80--90 cm back-paw bins as ``bin_means``.
    frame_distances_by_bin: tuple[tuple[float, ...], ...] = ()


@dataclass(frozen=True)
class MousePawDistanceSeries:
    """One mouse's trial-averaged stance distance within each beam bin."""

    day: str
    cage: str
    animal: str
    condition: str
    bin_means: tuple[float | None, ...]


@dataclass(frozen=True)
class GroupPawDistanceSummary:
    """Equal-mouse group mean and sample SD for every beam bin."""

    condition: str
    means: tuple[float | None, ...]
    standard_deviations: tuple[float | None, ...]
    mouse_counts: tuple[int, ...]


@dataclass(frozen=True)
class MousePawDistanceConsistency:
    """Within-mouse sample SD across trials for every beam bin."""

    day: str
    cage: str
    animal: str
    condition: str
    standard_deviations: tuple[float | None, ...]
    trial_counts: tuple[int, ...]


@dataclass(frozen=True)
class TrialPawDistanceWithinTrialVariation:
    """One trial's raw frame-to-frame distance variation in every beam bin."""

    day: str
    cage: str
    animal: str
    condition: str
    trial: int
    standard_deviations: tuple[float | None, ...]
    frame_counts: tuple[int, ...]


@dataclass(frozen=True)
class DayGroupPawDistanceSummary:
    """One equal-mouse group summary for each experimental day."""

    condition: str
    means: dict[str, float]
    standard_deviations: dict[str, float | None]
    mouse_counts: dict[str, int]


class BackFrontPawDistancePlotStore:
    """Create group and within-trial-variation charts from the frame-distance sheet."""

    def __init__(self, output_root: Path = OUTPUT_ROOT) -> None:
        self.output_root = output_root

    def result_dir(self, dataset: str) -> Path:
        return self.output_root / f"{dataset} Results"

    def chart_dir(self, dataset: str) -> Path:
        return self.result_dir(dataset) / CHART_DIRECTORY

    def refresh_dataset(self, dataset: str) -> dict[str, Path]:
        """Regenerate all back/front-paw distance charts for one dataset."""
        workbook_path = self.result_dir(dataset) / RESULTS_FILENAME
        if not workbook_path.exists():
            return {}

        conditions = ConditionMapStore(self.output_root).load(dataset)
        trials = self._read_trial_series(workbook_path, conditions)
        by_day: dict[str, list[TrialPawDistanceSeries]] = defaultdict(list)
        for series in trials:
            by_day[series.day].append(series)

        chart_dir = self.chart_dir(dataset)
        chart_dir.mkdir(parents=True, exist_ok=True)
        paths: dict[str, Path] = {}
        for day, day_trials in sorted(by_day.items(), key=lambda item: natural_day_key(item[0])):
            mice, groups = summarize_group_back_front_paw_distances(day_trials)
            group_path = chart_dir / f"{GROUP_PREFIX}{day}{FILE_SUFFIX}"
            self._write_svg(
                group_path,
                self._daily_group_svg(dataset, day, day_trials, mice, groups),
            )
            paths[f"group:{day}"] = group_path

            variation_trials, variation_mice, variation_groups = (
                summarize_back_front_paw_distance_within_trial_variation(day_trials)
            )
            variation_path = chart_dir / f"{WITHIN_TRIAL_VARIATION_PREFIX}{day}{FILE_SUFFIX}"
            self._write_svg(
                variation_path,
                self._daily_within_trial_variation_svg(
                    dataset,
                    day,
                    variation_trials,
                    variation_mice,
                    variation_groups,
                ),
            )
            paths[f"within_trial_variation:{day}"] = variation_path

        day_group_path = chart_dir / DAY_GROUP_FILENAME
        self._write_svg(
            day_group_path,
            self._day_bar_svg(
                dataset,
                summarize_day_by_day_back_front_paw_distances(trials),
                title="Day-by-day back/front paw-distance comparison",
                calculation_note=(
                    "For each day, each mouse is averaged across its trials and valid "
                    "10 cm bins from 0-90 cm before group calculation."
                ),
                comparison_note=(
                    "Colored bars are SHAM/STROKE mean distances; neutral-gray ranges and "
                    "whiskers are plus/minus 1 sample SD across mice."
                ),
                empty_note="No SHAM or STROKE back/front paw-distance data are available yet.",
                y_label="Back-paw to front-paw distance (cm)",
            ),
        )
        paths["day_group"] = day_group_path

        day_variation_path = chart_dir / DAY_WITHIN_TRIAL_VARIATION_FILENAME
        self._write_svg(
            day_variation_path,
            self._day_bar_svg(
                dataset,
                summarize_day_by_day_back_front_paw_distance_within_trial_variation(trials),
                title="Day-by-day back/front paw-distance within-trial variation",
                calculation_note=(
                    "For each 10 cm bin, calculate each trial's sample SD across raw valid "
                    "frames; each mouse contributes the mean of its trial/bin SDs."
                ),
                comparison_note=(
                    "Colored bars are SHAM/STROKE means; neutral-gray ranges and whiskers "
                    "are plus/minus 1 sample SD across mice. Lower SD means more consistent posture and gait."
                ),
                empty_note="No SHAM or STROKE back/front paw-distance variation data are available yet.",
                y_label="Within-trial paw-distance SD (cm; lower = more consistent)",
            ),
        )
        paths["day_within_trial_variation"] = day_variation_path

        live_names = {path.name for path in paths.values()}
        for prefix in (GROUP_PREFIX, WITHIN_TRIAL_VARIATION_PREFIX):
            for stale_path in chart_dir.glob(f"{prefix}*{FILE_SUFFIX}"):
                if stale_path.name not in live_names:
                    stale_path.unlink()
        # Only remove the known legacy trial-to-trial consistency artifacts;
        # no user-created files in the chart directory are touched.
        for stale_path in chart_dir.glob(f"{CONSISTENCY_PREFIX}*{FILE_SUFFIX}"):
            stale_path.unlink()
        obsolete_day_consistency = chart_dir / DAY_CONSISTENCY_FILENAME
        if obsolete_day_consistency.exists():
            obsolete_day_consistency.unlink()
        return paths

    @staticmethod
    def _read_trial_series(
        workbook_path: Path,
        conditions: dict[tuple[str, str], str],
    ) -> list[TrialPawDistanceSeries]:
        from openpyxl import load_workbook

        workbook = load_workbook(workbook_path, data_only=True, read_only=True)
        try:
            if SHEET_NAME not in workbook.sheetnames:
                return []
            sheet = workbook[SHEET_NAME]
            headers = [cell.value for cell in next(sheet.iter_rows(max_row=1), ())]
            index = {
                str(header): position
                for position, header in enumerate(headers)
                if header is not None
            }
            required = ("Day", "Cage", "Animal", "Trial")
            if not all(header in index for header in required):
                return []
            compact, separate_distances, separate_positions = _frame_columns(index)

            output: list[TrialPawDistanceSeries] = []
            for values in sheet.iter_rows(min_row=2, values_only=True):
                day = _cell_text(values, index["Day"])
                cage = _cell_text(values, index["Cage"])
                animal = _cell_text(values, index["Animal"])
                trial = _cell_int(values, index["Trial"])
                if not (day and cage and animal and trial):
                    continue

                by_bin: dict[int, list[float]] = defaultdict(list)
                for frame in set(compact) | set(separate_distances) | set(separate_positions):
                    distance, position = _frame_measurement(
                        values,
                        frame,
                        compact,
                        separate_distances,
                        separate_positions,
                    )
                    if distance is None or position is None:
                        continue
                    bin_start = _bin_start(position)
                    if bin_start is not None:
                        by_bin[bin_start].append(distance)
                if not by_bin:
                    continue
                output.append(
                    TrialPawDistanceSeries(
                        day=day,
                        cage=cage,
                        animal=animal,
                        condition=conditions.get((cage, animal), "UNASSIGNED"),
                        trial=trial,
                        bin_means=tuple(
                            statistics.fmean(by_bin[start]) if by_bin[start] else None
                            for start in BIN_STARTS_CM
                        ),
                        frame_distances_by_bin=tuple(
                            tuple(by_bin[start]) for start in BIN_STARTS_CM
                        ),
                    )
                )
            return output
        finally:
            workbook.close()

    @staticmethod
    def _write_svg(path: Path, text: str) -> None:
        temporary_path = path.with_suffix(f"{path.suffix}.tmp")
        try:
            temporary_path.write_text(text, encoding="utf-8")
            temporary_path.replace(path)
        finally:
            if temporary_path.exists():
                temporary_path.unlink()

